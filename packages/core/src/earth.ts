/**
 * 等距圆柱投影：经纬度 → 网格坐标。
 * 纵向裁到 84°N ~ 70°S：两极（尤其南极冰盖）在等距圆柱投影里会被严重放大，
 * 裁掉之后有人居住的区域能占到更多格子。
 */
export const EARTH_LAT_TOP = 84;
export const EARTH_LAT_BOTTOM = -70;

export function lonLatToCell(lon: number, lat: number): { x: number; y: number } {
  return {
    x: ((lon + 180) / 360) * MAP_W,
    y: ((EARTH_LAT_TOP - lat) / (EARTH_LAT_TOP - EARTH_LAT_BOTTOM)) * MAP_H,
  };
}

function inPolygon(x: number, y: number, poly: LonLat[]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const a = lonLatToCell(poly[i][0], poly[i][1]);
    const b = lonLatToCell(poly[j][0], poly[j][1]);
    if (a.y > y !== b.y > y && x < ((b.x - a.x) * (y - a.y)) / (b.y - a.y) + a.x) inside = !inside;
  }
  return inside;
}

/** 生成地球陆地掩码（1 = 陆地，0 = 海洋） */
export function earthLandMask(): Uint8Array {
  const mask = new Uint8Array(MAP_W * MAP_H);
  for (let gy = 0; gy < MAP_H; gy++) {
    const y = gy + 0.5;
    for (let gx = 0; gx < MAP_W; gx++) {
      const x = gx + 0.5;
      for (const poly of EARTH_LANDMASSES) {
        if (inPolygon(x, y, poly)) {
          mask[gy * MAP_W + gx] = 1;
          break;
        }
      }
    }
  }
  return mask;
}
